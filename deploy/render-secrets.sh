#!/usr/bin/env bash
# Generates the secret files the compose stack needs. Idempotent: existing secrets are NEVER rotated here
# (Postgres only reads its password when the data volume is first created — silently changing the file later
# would lock the app out of the database).
#
#   render-secrets.sh /opt/iconic
#
# Creates:   secrets/postgres_password   (600)   redis.conf (400, owned by the redis user in the container)
#            connection.env              (600)   DATABASE_URL / REDIS_URL for the app (loopback addresses)
set -euo pipefail
umask 077

DIR="${1:?usage: render-secrets.sh <install-dir>}"
PG_USER="${POSTGRES_USER:-iconic}"
PG_DB="${POSTGRES_DB:-iconic_connect}"
PG_PORT="${PG_PORT:-5433}"
REDIS_PORT="${REDIS_PORT:-6380}"
REDIS_MAXMEMORY="${REDIS_MAXMEMORY:-512mb}"
REDIS_UID="${REDIS_UID:-999}"            # uid of the `redis` user in redis:7-alpine

mkdir -p "$DIR/secrets"
# hex = URL-safe, so the password can sit inside a connection string without escaping.
gen() { openssl rand -hex 24; }

[ -s "$DIR/secrets/postgres_password" ] || gen > "$DIR/secrets/postgres_password"
[ -s "$DIR/secrets/redis_password" ]    || gen > "$DIR/secrets/redis_password"
PG_PASS="$(cat "$DIR/secrets/postgres_password")"
REDIS_PASS="$(cat "$DIR/secrets/redis_password")"

# Always re-render redis.conf from the stored password so config changes in this script take effect.
cat > "$DIR/redis.conf.tmp" <<CONF
# Generated by render-secrets.sh — do not edit by hand (re-generated on every provision).
bind 0.0.0.0
port 6379
protected-mode yes
requirepass ${REDIS_PASS}
appendonly yes
appendfsync everysec
maxmemory ${REDIS_MAXMEMORY}
maxmemory-policy noeviction
rename-command FLUSHALL ""
rename-command FLUSHDB ""
rename-command DEBUG ""
CONF
mv "$DIR/redis.conf.tmp" "$DIR/redis.conf"

cat > "$DIR/connection.env.tmp" <<ENV
# Generated by render-secrets.sh. Merge into the app's .env (provision workflow can do it for you).
DATABASE_URL=postgresql://${PG_USER}:${PG_PASS}@127.0.0.1:${PG_PORT}/${PG_DB}?sslmode=disable   # loopback only: the server speaks no TLS, and nothing leaves the host
REDIS_URL=redis://:${REDIS_PASS}@127.0.0.1:${REDIS_PORT}
ENV
mv "$DIR/connection.env.tmp" "$DIR/connection.env"

chmod 600 "$DIR/secrets/"* "$DIR/connection.env"
chmod 700 "$DIR/secrets"
if [ "$(id -u)" = "0" ]; then
  chown "$REDIS_UID:$REDIS_UID" "$DIR/redis.conf"   # container's redis user must be able to read it
  chmod 400 "$DIR/redis.conf"
else
  chmod 444 "$DIR/redis.conf"                         # non-root (local testing only)
fi
echo "secrets ready in $DIR (existing passwords were kept)"
